func TestPluginNamespace(t *testing.T) {
	tests := []struct {
		id   string
		want string
	}{
		{"text", "Text"},
		{"google-calendar", "GoogleCalendar"},
		{"my.plugin", "MyPlugin"},
		{"a_b-c.d", "ABCD"},
	}
	for _, tt := range tests {
		t.Run(tt.id, func(t *testing.T) {
			got := pluginNamespace(tt.id)
			if got != tt.want {
				t.Errorf("pluginNamespace(%q) = %q, want %q", tt.id, got, tt.want)
			}
		})
	}
}

