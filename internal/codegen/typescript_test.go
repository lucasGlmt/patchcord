func TestGenerateTypeScript_Connector(t *testing.T) {
	entry := &plugins.CatalogEntry{
		PluginID: "postgresql",
		Version:  "1.0.0",
		Actions: []plugins.ActionDescriptor{
			{
				ID:           "postgresql.query@1",
				InputSchema:  map[string]any{"type": "object", "properties": map[string]any{"sql": map[string]any{"type": "string"}}, "required": []any{"sql"}},
				OutputSchema: map[string]any{"type": "object"},
			},
		},
		Connectors: []plugins.ConnectorDescriptor{
			{
				Type:        "postgresql.connection@1",
				Description: "A PostgreSQL database connection.",
				ConfigSchema: map[string]any{
					"type": "object",
					"properties": map[string]any{
						"host":     map[string]any{"type": "string"},
						"port":     map[string]any{"type": "integer"},
						"database": map[string]any{"type": "string"},
					},
					"required": []any{"host", "database"},
				},
			},
		},
	}

	out, err := GenerateTypeScript(entry)
	if err != nil {
		t.Fatalf("GenerateTypeScript() error: %v", err)
	}
	s := string(out)

	if !strings.Contains(s, "export namespace Postgresql {") {
		t.Errorf("expected namespace\n\n%s", s)
	}
	if !strings.Contains(s, "export interface QueryInput {") {
		t.Errorf("expected action input\n\n%s", s)
	}
	if !strings.Contains(s, "export interface ConnectionConfig {") {
		t.Errorf("expected connector config\n\n%s", s)
	}
	if !strings.Contains(s, "host: string;") {
		t.Errorf("expected required host property\n\n%s", s)
	}
	if !strings.Contains(s, "port?: number;") {
		t.Errorf("expected optional port property\n\n%s", s)
	}
}

