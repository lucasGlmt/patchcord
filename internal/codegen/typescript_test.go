func TestSchemaToTS(t *testing.T) {
	tests := []struct {
		name   string
		schema map[string]any
		want   string
	}{
		{"string", map[string]any{"type": "string"}, "string"},
		{"number", map[string]any{"type": "number"}, "number"},
		{"integer", map[string]any{"type": "integer"}, "number"},
		{"boolean", map[string]any{"type": "boolean"}, "boolean"},
		{"no type", map[string]any{}, "unknown"},
		{"nil map", nil, "unknown"},
		{
			"enum",
			map[string]any{"enum": []any{"a", "b", "c"}},
			`"a" | "b" | "c"`,
		},
		{
			"array of strings",
			map[string]any{"type": "array", "items": map[string]any{"type": "string"}},
			"Array<string>",
		},
		{
			"array without items",
			map[string]any{"type": "array"},
			"Array<unknown>",
		},
		{
			"object without properties",
			map[string]any{"type": "object"},
			"Record<string, unknown>",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			schema := tt.schema
			if schema == nil {
				schema = map[string]any{}
			}
			got := schemaToTS(schema, "")
			if got != tt.want {
				t.Errorf("schemaToTS() = %q, want %q", got, tt.want)
			}
		})
	}
}

func TestGenerateTypeScript_SimpleAction(t *testing.T) {
	entry := &plugins.CatalogEntry{
		PluginID: "text",
		Version:  "1.0.0",
		Actions: []plugins.ActionDescriptor{
			{
				ID:          "text.uppercase@1",
				Description: "Converts a string to upper case.",
				InputSchema: map[string]any{
					"type": "object",
					"properties": map[string]any{
						"value": map[string]any{
							"type":        "string",
							"description": "The string to convert.",
						},
					},
					"required": []any{"value"},
				},
				OutputSchema: map[string]any{
					"type": "object",
					"properties": map[string]any{
						"value": map[string]any{
							"type":        "string",
							"description": "value, converted to upper case.",
						},
					},
					"required": []any{"value"},
				},
			},
		},
	}

	out, err := GenerateTypeScript(entry)
	if err != nil {
		t.Fatalf("GenerateTypeScript() error: %v", err)
	}
	s := string(out)

	mustContain := []string{
		"// Code generated by patchcord dev codegen",
		"DO NOT EDIT",
		"// Plugin: text v1.0.0",
		"export namespace Text {",
		"/** Converts a string to upper case. */",
		"export interface UppercaseInput {",
		"/** The string to convert. */",
		"value: string;",
		"export interface UppercaseOutput {",
	}
	for _, want := range mustContain {
		if !strings.Contains(s, want) {
			t.Errorf("output missing %q\n\nfull output:\n%s", want, s)
		}
	}
}

func TestGenerateTypeScript_OptionalProperties(t *testing.T) {
	entry := &plugins.CatalogEntry{
		PluginID: "test",
		Version:  "0.1.0",
		Actions: []plugins.ActionDescriptor{
			{
				ID: "test.do@1",
				InputSchema: map[string]any{
					"type": "object",
					"properties": map[string]any{
						"name":  map[string]any{"type": "string"},
						"label": map[string]any{"type": "string"},
					},
					"required": []any{"name"},
				},
				OutputSchema: map[string]any{},
			},
		},
	}

	out, err := GenerateTypeScript(entry)
	if err != nil {
		t.Fatalf("GenerateTypeScript() error: %v", err)
	}
	s := string(out)

	// "name" is required → no "?"
	if !strings.Contains(s, "name: string;") {
		t.Errorf("expected required property without '?'\n\n%s", s)
	}
	// "label" is optional → has "?"
	if !strings.Contains(s, "label?: string;") {
		t.Errorf("expected optional property with '?'\n\n%s", s)
	}
}

