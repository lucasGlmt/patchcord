// Scaffold writes a minimal standalone Go plugin module using id as both
// the plugin id and Go module path. See ScaffoldWithModule for details.
func Scaffold(dir, id, version string) error {
	return ScaffoldWithModule(dir, id, version, id)
}

// ScaffoldWithModule writes a minimal standalone Go plugin module
// (go.mod, main.go, one example action, manifest.json, README.md,
// Makefile, .gitignore) into dir. The generated plugin imports only the
// public Go SDK and the package manifest declares an executable for the
// current platform, enough to `go build` then `plugin pack` without
// hand-editing the manifest. It returns an error if dir already exists and
// is not empty.
func ScaffoldWithModule(dir, id, version, modulePath string) error {
	if err := ensureEmptyDir(dir); err != nil {
		return err
	}

	if modulePath == "" {
		modulePath = id
	}

	goMod := fmt.Sprintf(scaffoldGoModTemplate, modulePath, scaffoldGoVersion)
	if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte(goMod), 0o644); err != nil {
		return fmt.Errorf("write go.mod: %w", err)
	}

	mainGo := fmt.Sprintf(scaffoldMainGo, id, version)
	if err := os.WriteFile(filepath.Join(dir, "main.go"), []byte(mainGo), 0o644); err != nil {
		return fmt.Errorf("write main.go: %w", err)
	}

	platform := runtime.GOOS + "-" + runtime.GOARCH
	manifest := packageManifestJSON{
		SchemaVersion:   1,
		Kind:            packageManifestKind,
		ID:              id,
		Version:         version,
		ProtocolVersion: CurrentProtocolVersion,
		Permissions:     []string{},
		Executables: map[string]string{
			platform: fmt.Sprintf("binaries/%s/plugin", platform),
		},
	}
	manifestJSON, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil {
		return fmt.Errorf("encode manifest.json: %w", err)
	}
	if err := os.WriteFile(filepath.Join(dir, PackageManifestFileName), manifestJSON, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", PackageManifestFileName, err)
	}

	readme := fmt.Sprintf(scaffoldReadmeTemplate, id, platform, id, version, id, version, platform)
	if err := os.WriteFile(filepath.Join(dir, "README.md"), []byte(readme), 0o644); err != nil {
		return fmt.Errorf("write README.md: %w", err)
	}

	makefile := fmt.Sprintf(scaffoldMakefileTemplate, id, version)
	if err := os.WriteFile(filepath.Join(dir, "Makefile"), []byte(makefile), 0o644); err != nil {
		return fmt.Errorf("write Makefile: %w", err)
	}

	if err := os.WriteFile(filepath.Join(dir, ".gitignore"), []byte(scaffoldGitignore), 0o644); err != nil {
		return fmt.Errorf("write .gitignore: %w", err)
	}

	if err := os.WriteFile(filepath.Join(dir, "AGENTS.md"), []byte(scaffoldAgentsMD), 0o644); err != nil {
		return fmt.Errorf("write AGENTS.md: %w", err)
	}

	return nil
}

// ensureEmptyDir creates dir if it doesn't exist yet, or errors if it
// exists and already has entries — same rule as apps.Scaffold and
// bundles.Scaffold.
func ensureEmptyDir(dir string) error {
	entries, err := os.ReadDir(dir)
	if err == nil {
		if len(entries) > 0 {
			return fmt.Errorf("%q already exists and is not empty", dir)
		}
		return nil
	}
	if !os.IsNotExist(err) {
		return fmt.Errorf("check %q: %w", dir, err)
	}

	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("create %q: %w", dir, err)
	}
	return nil
}
