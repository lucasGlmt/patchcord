const scaffoldMainGo = `package main

import (
	"context"
	"fmt"
	"os"

	patchcord "github.com/lucasglmt/patchcord/sdk/go-plugin"
)

type exampleAction struct{}

func (exampleAction) ID() string { return "example.echo@1" }

func (exampleAction) Description() string { return "Returns the given value unchanged." }

func (exampleAction) InputSchema() patchcord.Schema {
	return patchcord.Schema{
		"type": "object",
		"properties": map[string]any{
			"value": map[string]any{"type": "string"},
		},
		"required": []any{"value"},
	}
}

func (exampleAction) OutputSchema() patchcord.Schema {
	return patchcord.Schema{
		"type": "object",
		"properties": map[string]any{
			"value": map[string]any{"type": "string"},
		},
		"required": []any{"value"},
	}
}

func (exampleAction) Run(_ context.Context, input patchcord.ActionInput, _ *patchcord.ConnectorConfig) (patchcord.ActionOutput, error) {
	value, ok := input["value"].(string)
	if !ok {
		return nil, fmt.Errorf("input %%q must be a string", "value")
	}
	return patchcord.ActionOutput{"value": value}, nil
}

func main() {
	plugin := patchcord.Plugin{
		Manifest: patchcord.Manifest{
			ID:      %q,
			Version: %q,
		},
		Actions: []patchcord.Action{
			exampleAction{},
		},
	}

	if err := patchcord.Serve(plugin); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
`

